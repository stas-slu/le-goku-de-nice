export const STRINGS: Record<Lang, typeof fr> = { fr, en };
export type StringKey = keyof typeof fr;

let lang: Lang = 'fr';
try {
  const saved = localStorage.getItem('gdn_lang');
  if (saved === 'fr' || saved === 'en') lang = saved;
  else if (typeof navigator !== 'undefined' && !navigator.language.toLowerCase().startsWith('fr')) lang = 'en';
} catch {
  // storage unavailable: keep the default
}

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang): void {
  lang = l;
  try {
    localStorage.setItem('gdn_lang', l);
  } catch {
    // ignore
  }
}

export function t(key: StringKey | string): string {
  const table = STRINGS[lang] as Record<string, string>;
  return table[key] ?? (STRINGS.fr as Record<string, string>)[key] ?? key;
}
